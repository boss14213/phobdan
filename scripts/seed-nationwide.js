async function seedNationwide() {
  console.log(`Starting insertion of ${NATIONWIDE_CHECKPOINTS.length} nationwide checkpoints...`);

  const chunkSize = 15;
  let totalInserted = 0;

  for (let i = 0; i < NATIONWIDE_CHECKPOINTS.length; i += chunkSize) {
    const chunk = NATIONWIDE_CHECKPOINTS.slice(i, i + chunkSize);
    const { data, error } = await supabase.from('checkpoints').upsert(chunk, { onConflict: 'id' });

    if (error) {
      console.error(`Error inserting chunk ${i / chunkSize + 1}:`, error.message);
    } else {
      totalInserted += chunk.length;
      console.log(`Chunk ${i / chunkSize + 1} (${chunk.length} items) upserted successfully.`);
    }
  }

  const { count, error: countErr } = await supabase.from('checkpoints').select('*', { count: 'exact', head: true });
  console.log(`Finished! Total checkpoints in Supabase database: ${count}`);
}

